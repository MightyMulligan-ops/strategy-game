import { randomUUID } from "node:crypto";
import { afterAll, afterEach, beforeAll, describe, expect, it } from "vitest";
import { resolveTurn, SEEDED_MOVEMENT_POLICY, SIMULATION_VERSION } from "@strategy-game/game-engine";
import { FrozenTurnInputSchema } from "@strategy-game/shared-types/server";
import { createDatabaseClient, MatchRepository } from "../src/index.js";
import { testDatabaseUrl } from "../src/environment.js";
import { json, orderRows } from "../src/mappings.js";

// Normal unit runs explicitly skip this suite, even if DATABASE_URL is set.
describe.skipIf(process.env.RUN_DATABASE_TESTS !== "1")("PostgreSQL persistence (live database required)", () => {
  let client: ReturnType<typeof createDatabaseClient>;
  let repository: MatchRepository;
  const matches: string[] = [];
  const identityIds: string[] = [];
  const pinned = {
    schemaVersion: 1, ruleset: { rulesetId: "baseline", version: "1" },
    simulationVersion: SIMULATION_VERSION, movementTieBreakPolicy: SEEDED_MOVEMENT_POLICY
  };
  const move = (orderId: string) => ({ orderId, type: "move" as const, stackId: "stack", destination: { x: 5, y: 2 } });
  const attack = { orderId: "attack", type: "attack" as const, stackId: "stack", targetId: "target" };
  beforeAll(async () => {
    client = createDatabaseClient(testDatabaseUrl(process.env.TEST_DATABASE_URL));
    repository = new MatchRepository(client);
    await client.$connect();
  }, 10_000);
  afterEach(async () => {
    if (!client || matches.length === 0) return;
    await deleteFixtures([...matches], [...identityIds]);
    // Retain ownership records if cleanup fails, so a later attempt can retry.
    matches.length = 0;
    identityIds.length = 0;
  }, 10_000);
  afterAll(async () => { if (client) await client.$disconnect(); });

  async function deleteFixtures(matchIds: readonly string[], createdIdentityIds: readonly string[]) {
    if (matchIds.length === 0) return;
    const scope = { matchId: { in: [...matchIds] } };
    // NO ACTION cross-references require explicit child-before-parent deletion.
    // Every statement is scoped to IDs generated by this test process; do not
    // delete by a test-name prefix or rely on competing Match cascade paths.
    await client.$transaction(async (tx) => {
      await tx.orderDependency.deleteMany({ where: scope });
      await tx.resolutionResult.deleteMany({ where: scope });
      await tx.frozenTurnInputRecord.deleteMany({ where: scope });
      await tx.playerOrder.deleteMany({ where: scope });
      await tx.playerSubmissionRevision.deleteMany({ where: scope });
      await tx.playerTurnState.deleteMany({ where: scope });
      await tx.turn.deleteMany({ where: scope });
      await tx.gameSnapshotRecord.deleteMany({ where: scope });
      await tx.match.deleteMany({ where: { id: { in: [...matchIds] } } });
      await tx.playerIdentity.deleteMany({ where: {
        id: { in: [...createdIdentityIds] }, participants: { none: {} }
      } });
    });
  }

  async function fresh() {
    const id = `test-${randomUUID()}`;
    matches.push(id);
    const players = ["alice", "bob"].map((playerId) => ({ schemaVersion: 1, gameId: id, playerId, active: true }));
    const identities = players.map(({ playerId }) => ({ playerId, identityId: `${id}:${playerId}` }));
    identityIds.push(...identities.map((identity) => identity.identityId));
    const snapshot = {
      schemaVersion: 1, ruleset: pinned.ruleset, simulationVersion: SIMULATION_VERSION,
      snapshotId: `snapshot:${id}`, config: { schemaVersion: 1, gameId: id, turnDurationMs: 1_000 },
      completedTurnNumber: 0, stateVersion: 0, players
    };
    await repository.createMatch(snapshot, pinned, identities, 10_000);
    return id;
  }
  const envelope = (id: string, expectedRevision: number, action: object) => ({
    schemaVersion: 1, gameId: id, turnNumber: 1, expectedRevision, ...action
  });
  const send = (id: string, actor: string, revision: number, action: object) =>
    repository.submitCommand(id, 1, actor, envelope(id, revision, action), () => 10_001);

  it("cleans only selected fixture IDs and leaves another populated match intact", async () => {
    const removed = await fresh();
    const retained = await fresh();
    await send(removed, "alice", 0, { kind: "replace_orders", orders: [move("first"), move("second")] });
    await client.orderDependency.create({ data: {
      matchId: removed, turnNumber: 1n, playerId: "alice", orderId: "second", prerequisiteOrderId: "first"
    } });
    await send(retained, "alice", 0, { kind: "replace_orders", orders: [move("retained")] });
    const before = await repository.loadTurn(retained, 1);
    const removedIdentities = [`${removed}:alice`, `${removed}:bob`];
    await deleteFixtures([removed], removedIdentities);
    expect(await client.match.findUnique({ where: { id: removed } })).toBeNull();
    expect(await client.playerIdentity.count({ where: { id: { in: removedIdentities } } })).toBe(0);
    expect(await repository.loadTurn(retained, 1)).toEqual(before);
    expect(await client.playerIdentity.count({ where: { id: { in: [`${retained}:alice`, `${retained}:bob`] } } })).toBe(2);
    // Already-deleted tracked IDs are safe for afterEach to retry as well.
  });

  it("persists revisions, Ready clearing, reordering, and cancellation without mutating game state", async () => {
    const id = await fresh();
    expect((await send(id, "alice", 0, { kind: "replace_orders", orders: [move("first"), attack, move("second")] })).accepted).toBe(true);
    await send(id, "alice", 1, { kind: "set_ready", ready: true });
    await send(id, "alice", 2, { kind: "replace_orders", orders: [move("second"), move("first")] });
    expect((await repository.loadTurn(id, 1)).state.drafts[0]).toMatchObject({ ready: false, revision: 3 });
    await send(id, "alice", 3, { kind: "cancel_order", orderId: "second" });
    const active = await client.playerOrder.findMany({ where: { matchId: id, active: true } });
    expect(active.map((order) => [order.orderId, order.moveNumber])).toEqual([["first", 1]]);
    expect(await client.playerSubmissionRevision.count({ where: { matchId: id, playerId: "alice" } })).toBe(5);
    expect(await client.playerOrder.count({ where: { matchId: id, active: false } })).toBe(2);
    expect((await client.match.findUniqueOrThrow({ where: { id } })).currentStateVersion).toBe(0n);
  });

  it("serializes competing revisions so only one stale-base submission is accepted", async () => {
    const id = await fresh();
    const results = await Promise.all([
      send(id, "alice", 0, { kind: "replace_orders", orders: [move("first")] }),
      send(id, "alice", 0, { kind: "replace_orders", orders: [attack] })
    ]);
    expect(results.filter((result) => result.accepted)).toHaveLength(1);
    expect(results.find((result) => !result.accepted)).toMatchObject({ reason: "stale_revision" });
    expect((await repository.loadTurn(id, 1)).state.drafts[0]?.revision).toBe(1);
  });

  it("atomically closes on Ready and freezes the final ordered queues", async () => {
    const id = await fresh();
    await send(id, "alice", 0, { kind: "replace_orders", orders: [move("second"), move("first")] });
    await send(id, "alice", 1, { kind: "set_ready", ready: true });
    await send(id, "bob", 0, { kind: "set_ready", ready: true });
    const stored = await client.frozenTurnInputRecord.findUniqueOrThrow({ where: { matchId_turnNumber: { matchId: id, turnNumber: 1n } } });
    const frozen = FrozenTurnInputSchema.parse(stored.payload);
    expect(frozen.turn).toMatchObject({ status: "closed", closeReason: "all_ready" });
    expect(frozen.playerOrders[0]?.orders.map((order) => order.orderId)).toEqual(["second", "first"]);
    expect(await send(id, "alice", 2, { kind: "cancel_order", orderId: "second" })).toMatchObject({ accepted: false, reason: "turn_closed" });
    expect(await client.frozenTurnInputRecord.count({ where: { matchId: id } })).toBe(1);
  });

  it("persists deadline closure and frozen input even when rejecting a malformed late command", async () => {
    const id = await fresh();
    expect(await repository.submitCommand(id, 1, "alice", null, () => 11_000)).toMatchObject({ accepted: false, reason: "turn_closed" });
    expect((await repository.loadTurn(id, 1)).state.turn).toMatchObject({ status: "closed", closeReason: "deadline", closedAtMs: 11_000 });
    expect(await client.frozenTurnInputRecord.count({ where: { matchId: id } })).toBe(1);
  });

  it("rolls back a closure transaction that omits its required frozen input", async () => {
    const id = await fresh();
    await expect(client.$transaction(async (tx) => {
      await tx.turn.update({ where: { matchId_number: { matchId: id, number: 1n } }, data: {
        status: "CLOSED", closeReason: "DEADLINE", closedAtMs: 11_000n, lastObservedAtMs: 11_000n
      } });
    })).rejects.toThrow();
    expect((await repository.loadTurn(id, 1)).state.turn.status).toBe("open");
  });

  it("enforces database uniqueness for order IDs and both kinds of active queue position", async () => {
    const id = await fresh();
    await send(id, "alice", 0, { kind: "replace_orders", orders: [move("first")] });
    const row = orderRows(id, 1, { playerId: "alice", revision: 1, ready: false, orders: [move("first")] })[0]!;
    await expect(client.playerOrder.create({ data: row })).rejects.toThrow();
    await expect(client.playerOrder.create({ data: { ...row, orderId: "duplicate-position", payload: json(move("duplicate-position")), moveNumber: 2 } })).rejects.toThrow();
    await expect(client.playerOrder.create({ data: { ...row, orderId: "duplicate-move", payload: json(move("duplicate-move")), draftPosition: 2 } })).rejects.toThrow();
  });

  it("rejects updates to fixed configuration and frozen inputs", async () => {
    const id = await fresh();
    await expect(client.matchConfiguration.update({ where: { matchId: id }, data: { turnDurationMs: 2_000n } })).rejects.toThrow();
    await repository.observeDeadline(id, 1, () => 11_000);
    await expect(client.frozenTurnInputRecord.update({ where: { matchId_turnNumber: { matchId: id, turnNumber: 1n } }, data: { payload: {} } })).rejects.toThrow();
    await expect(client.playerTurnState.update({ where: { matchId_turnNumber_playerId: { matchId: id, turnNumber: 1n, playerId: "alice" } }, data: { ready: true } })).rejects.toThrow();
  });

  it("recovers a pinned resolution on a new client and commits retries exactly once", async () => {
    const id = await fresh();
    await repository.observeDeadline(id, 1, () => 11_000);
    await repository.prepareResolution(id, 1, 42);
    const restartedClient = createDatabaseClient(testDatabaseUrl(process.env.TEST_DATABASE_URL));
    try {
      const restarted = new MatchRepository(restartedClient);
      const context = await restarted.prepareResolution(id, 1);
      expect(context.seed).toBe(42);
      await expect(restarted.prepareResolution(id, 1, 43)).rejects.toThrow("already pinned");
      const outcome = resolveTurn(context.snapshot, context.frozen, context.pinned, context.seed);
      if (!outcome.ok) throw new Error(outcome.error.message);
      const committed = await Promise.all([
        repository.commitResolution(id, 1, outcome.result), restarted.commitResolution(id, 1, outcome.result)
      ]);
      expect(committed[0]).toEqual(committed[1]);
      expect(await restarted.commitResolution(id, 1, outcome.result)).toEqual(outcome.result);
      expect(await client.resolutionResult.count({ where: { matchId: id } })).toBe(1);
      expect(await client.gameSnapshotRecord.count({ where: { matchId: id } })).toBe(2);
      expect((await client.match.findUniqueOrThrow({ where: { id } })).currentStateVersion).toBe(1n);
      const next = await restarted.openFollowingTurn(id, 1, 12_000);
      expect(next.turn).toMatchObject({ turnNumber: 2, status: "open", deadlineAtMs: 13_000 });
      expect((await restarted.loadTurn(id, 2)).state.config.turnDurationMs).toBe(1_000);
    } finally { await restartedClient.$disconnect(); }
  });

  it("cannot commit an apparent empty result for a nonempty frozen queue", async () => {
    const id = await fresh();
    await send(id, "alice", 0, { kind: "replace_orders", orders: [move("first")] });
    await repository.observeDeadline(id, 1, () => 11_000);
    const context = await repository.prepareResolution(id, 1, 42);
    const fabricated = resolveTurn(context.snapshot, {
      ...context.frozen, playerOrders: context.frozen.playerOrders.map((player) => ({ ...player, orders: [] }))
    }, context.pinned, 42);
    if (!fabricated.ok) throw new Error(fabricated.error.message);
    await expect(repository.commitResolution(id, 1, fabricated.result)).rejects.toThrow("stored frozen");
    expect(await client.resolutionResult.count({ where: { matchId: id } })).toBe(0);
    expect((await client.match.findUniqueOrThrow({ where: { id } })).currentStateVersion).toBe(0n);
  });

  it("stores scoped future prerequisites but refuses edits until dependency policies are approved", async () => {
    const id = await fresh();
    await send(id, "alice", 0, { kind: "replace_orders", orders: [move("first"), move("second")] });
    const dependency = { matchId: id, turnNumber: 1n, playerId: "alice", orderId: "second", prerequisiteOrderId: "first", requiredOutputRef: "future-output" };
    await client.orderDependency.create({ data: dependency });
    await expect(client.orderDependency.create({ data: { ...dependency, orderId: "first" } })).rejects.toThrow();
    await expect(send(id, "alice", 1, { kind: "cancel_order", orderId: "first" })).rejects.toMatchObject({ code: "dependencies_not_supported" });
    expect((await repository.loadTurn(id, 1)).state.drafts[0]?.orders).toHaveLength(2);
  });
});
